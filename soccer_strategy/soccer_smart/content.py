"""Authored tactical situations and unscored practice cards for Soccer Smart Lab."""

from dataclasses import dataclass

from .model import Point


@dataclass(frozen=True)
class ActorSpec:
    key: str
    label: str
    team: str
    position: Point
    approach: Point | None = None
    run_to: Point | None = None


@dataclass(frozen=True)
class ChoiceSpec:
    key: str
    label: str
    target: Point
    rating: int
    explanation: str
    outcome: str
    ball_end: Point
    action_kind: str


@dataclass(frozen=True)
class VariantSpec:
    variant: str
    cue: str
    ball: Point
    ball_from: Point
    actors: tuple[ActorSpec, ...]
    choices: tuple[ChoiceSpec, ...]
    coach_note: str
    ball_state: str = "controlled"
    shot_window: Point | None = None


@dataclass(frozen=True)
class TopicSpec:
    topic: int
    title: str
    role: str
    groups: tuple[str, ...]
    focus: str
    variants: tuple[VariantSpec, ...]


@dataclass(frozen=True)
class CardSpec:
    id: str
    title: str
    groups: tuple[str, ...]
    summary: str
    adult_prompt: str
    actors: tuple[ActorSpec, ...]
    ball_start: Point
    ball_end: Point


